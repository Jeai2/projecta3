import type { CheoneumSpreadId } from "./cheoneum.types";

/**
 * 천음 해석 씨앗.
 *
 * 이 파일은 "완성된 답변 문장"을 저장하는 곳이 아니라,
 * 화선/화영이 답변을 만들 때 참고할 의미 재료를 저장하는 곳입니다.
 *
 * 작성 원칙:
 * - 한 문장을 그대로 출력시키려 하기보다, 의미가 흔들리지 않게 여러 표현 씨앗을 둡니다.
 * - AI는 expressionSeeds를 그대로 복사하지 않고 말투에 맞춰 변주해야 합니다.
 * - raw 계산값(간지/십성)은 cheoneum-divination.service.ts에서 만들고,
 *   이 파일은 카드가 가진 상징과 질문 문맥별 방향을 담당합니다.
 */

export type CheoneumReadingContext = "daily" | "relationship" | "choice" | "flow" | "caution";

export interface CheoneumMeaningSeed {
  /** 카드의 중심 장면. 그대로 말하기보다 의미 방향으로 사용합니다. */
  coreImage: string;

  /** 카드가 품은 의미 영역. 짧은 명사/구 위주로 작성합니다. */
  semanticField: string[];

  /**
   * 답변에서 변주될 수 있는 표현 씨앗.
   * 그대로 복붙될 수도 있으므로, 너무 문학적으로 완성된 문장만 넣기보다
   * 여러 말투로 바꾸기 쉬운 문장을 3~5개 정도 둡니다.
   */
  expressionSeeds: string[];

  /**
   * 질문 맥락별 해석 방향.
   * daily: 오늘 운세 / 한 장 뽑기
   * relationship: 연애, 관계, 상대 마음
   * choice: 할까 말까, A/B 선택
   * flow: 시기, 흐름, 앞으로의 전개
   * caution: 경계할 점
   */
  readingBias: Record<CheoneumReadingContext, string[]>;

  /**
   * 특정 스프레드에서만 강조할 해석.
   * 필요 없으면 비워둬도 됩니다.
   */
  spreadBias?: Partial<Record<CheoneumSpreadId, string[]>>;

  /**
   * 답변에서 그대로 반복되면 어색한 표현.
   * AI에게 "이 표현은 그대로 말하지 말고 변주하라"고 알려줄 때 씁니다.
   */
  avoidExactPhrases?: string[];
}


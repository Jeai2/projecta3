/**
 * 메시지에서 매칭되는 분야를 모두 찾아 반환.
 * 여러 분야가 동시에 매칭될 수 있음 (예: "이직하고 이혼도 고민" → 직업 + 결혼)
 */
export function matchCategories(message: string): CategoryConfig[] {
  const matched: CategoryConfig[] = [];
  for (const config of SERIOUS_CATEGORIES) {
    if (config.keywords.some((kw) => message.includes(kw))) {
      matched.push(config);
    }
  }
  return matched;
}
